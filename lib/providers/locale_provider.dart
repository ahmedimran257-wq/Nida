class LocaleState {
  final String languageCode;
  final TextDirection textDirection;
  final bool isNastaliq;

  LocaleState({
    required this.languageCode,
    required this.textDirection,
    required this.isNastaliq,
  });

  LocaleState copyWith({
    String? languageCode,
    TextDirection? textDirection,
    bool? isNastaliq,
  }) {
    return LocaleState(
      languageCode: languageCode ?? this.languageCode,
      textDirection: textDirection ?? this.textDirection,
      isNastaliq: isNastaliq ?? this.isNastaliq,
    );
  }
}

class LocaleNotifier extends StateNotifier<LocaleState> {
  LocaleNotifier() : super(LocaleState(
    languageCode: 'en',
    textDirection: TextDirection.ltr,
    isNastaliq: false,
  )) {
    _loadSavedLocale();
  }

  static const String _prefKey = 'nida_selected_language';

  Future<void> _loadSavedLocale() async {
    final prefs = await SharedPreferences.getInstance();
    final savedCode = prefs.getString(_prefKey) ?? 'en';
    setLanguage(savedCode);
  }

  Future<void> setLanguage(String code) async {
    final prefs = await SharedPreferences.getInstance();
    await prefs.setString(_prefKey, code);

    final isRTL = code == 'ur' || code == 'ar';
    state = LocaleState(
      languageCode: code,
      textDirection: isRTL ? TextDirection.rtl : TextDirection.ltr,
      isNastaliq: code == 'ur',
    );
  }
}

final localeProvider = StateNotifierProvider<LocaleNotifier, LocaleState>((ref) {
  return LocaleNotifier();
});

